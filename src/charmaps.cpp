    CharmapInfo init_charmap(const std::string & cm_name)
    {
        CharmapInfo info;

        if (cm_name == "agat") {
            info.charmap = &agat_charmap;
            info.crlf = {0x8d, 0x0D};
        } else
        if (cm_name == "apple2") {
            info.charmap = &apple2_charmap;
            info.crlf = {0x8d, 0x0D};
        } else
        if (cm_name == "apple2c") {
            info.charmap = &apple2c_charmap;
            info.crlf = {0x8d, 0x0D};
        } else
        if (cm_name == "ascii") {
            info.charmap = &ascii_charmap;
            info.crlf = {0x0D};
            info.ignore = {0x0A};
            info.txt_end = {0x1A};
            info.tab = 8;
        } else
        if (cm_name == "koi7_n0_n1") {
            info.charmap = &koi7_n0_n1_charmap;
            info.crlf = {0x8D, 0x0D};
            info.ignore = {0x0A};
            info.txt_end = {0x1A};
            info.tab = 8;
            info.is_koi7 = true;
        } else
        if (cm_name == "koi7_n2") {
            info.charmap = &koi7_n2_charmap;
            info.crlf = {0x0D};
            info.ignore = {0x0A};
            info.txt_end = {0x1A};
            info.tab = 8;
        } else
        if (cm_name == "onix") {
            // Onix documents are KOI-8, but they are laid out by a word processor:
            // $1A is the padding a justified line was stretched with, $1C and $1D switch
            // the emphasis of a heading on and off, and $1A is emphatically not an end of
            // text marker the way CP/M uses it.
            info.charmap = &koi8_r_charmap;
            info.crlf = {0x0D};
            info.spaces = {0x1A};
            info.ignore = {0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08,
                           0x0A, 0x0B, 0x0C, 0x0E, 0x0F,
                           0x10, 0x11, 0x12, 0x13, 0x14, 0x15, 0x16, 0x17, 0x18, 0x19,
                           0x1B, 0x1C, 0x1D, 0x1E, 0x1F};
            info.tab = 8;
        } else
        if (cm_name == "koi8_r") {
            info.charmap = &koi8_r_charmap;
            info.crlf = {0x0D};
            info.ignore = {0x0A};
            info.txt_end = {0x1A};
            info.tab = 8;
        } else
        if (cm_name == "koi8_m") {
            info.charmap = &koi8_m_charmap;
            info.crlf = {0x0D};
            info.ignore = {0x0A};
            info.txt_end = {0x1A};
            info.tab = 8;
        } else
        if (cm_name == "cp866") {
            info.charmap = &cp866_charmap;
            info.crlf = {0x0D};
            info.ignore = {0x0A};
            info.txt_end = {0x1A};
            info.tab = 8;
        } else
        if (cm_name == "cp1251") {
            info.charmap = &cp1251_charmap;
            info.crlf = {0x0D};
            info.ignore = {0x0A};
            info.txt_end = {0x1A};
            info.tab = 8;
        } else
        if (cm_name == "iso8859_5") {
            info.charmap = &iso8859_5_charmap;
            info.crlf = {0x0D};
            info.ignore = {0x0A};
            info.txt_end = {0x1A};
            info.tab = 8;
        } else {
            // TODO: Other encodings;
        }

        return info;
    }

